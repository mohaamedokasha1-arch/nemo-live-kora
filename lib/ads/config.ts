/**
 * ═══════════════════════════════════════════════════════════════════════════════
 *  إعداد المساحات الإعلانية — مصدر واحد للحقيقة (Server + Client)
 * ═══════════════════════════════════════════════════════════════════════════════
 *  لماذا ملف منفصل؟ لأن مكوّن الإعلان ملف عميل (`'use client'`)، ومكوّنات الخادم
 *  (صفحات المباريات والبث) تستطيع استدعاء **دوال عادية** من ملف عادي، لكن لا تستطيع
 *  استدعاء دوال من ملف عميل. وجود الفحص هنا يسمح للخادم بأن يقرّر **قبل** إرسال أي
 *  شيء إلى المتصفح: هل هناك إعلان مضبوط؟ إن لم يكن، فلا يُرسل المكوّن أصلًا، وبذلك لا
 *  يظهر أي أثر لمرحلة الإعداد — لا في الصفحة ولا حتى في بيانات الصفحة (RSC payload).
 *
 *  `process.env.NEXT_PUBLIC_*` تُستبدل وقت البناء في الخادم والعميل معًا، والقيمة
 *  الواحدة تُقرأ من هنا، فلا يمكن أن تختلف نتيجة الخادم عن نتيجة العميل.
 */

/** معرّف الناشر (مثال: ca-pub-1234567890123456). الفراغ = لا إعلانات. */
export const ADSENSE_CLIENT_ID = (process.env.NEXT_PUBLIC_ADSENSE_CLIENT || '').trim();

/** تنظيف رقم الوحدة الإعلانية القادم من البيئة أو من الخصائص. */
export function resolveAdSlotId(raw?: string | null): string {
  return (raw || '').trim();
}

/**
 * هل يجب رسم مساحة إعلانية بهذا الرقم؟ لا إلا إذا كان معرّف الناشر ورقم الوحدة
 * صالحين معًا. الدالة تُستخدم في مكوّنات الخادم لتخطي الرسم كليًا عند عدم الضبط.
 */
export function shouldRenderAdSlot(raw?: string | null): boolean {
  return Boolean(ADSENSE_CLIENT_ID && resolveAdSlotId(raw));
}
