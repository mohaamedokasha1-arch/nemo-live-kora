import React from 'react';
import {
  buildGaInlineSnippet,
  buildGaScriptUrl,
  isGoogleAnalyticsActive,
  resolveGaMeasurementId,
} from '@/lib/analytics/google-analytics';

/**
 * ═══════════════════════════════════════════════════════════════════════════════
 *  Google Analytics (gtag.js) — الوسم الذي يطلبه كود Google حرفيًا
 * ═══════════════════════════════════════════════════════════════════════════════
 *  الموضع: **أول عنصر داخل `<head>`** في التخطيط العام (`app/layout.tsx`)، أي في كل
 *  صفحات الموقع بلا استثناء (الرئيسية، التواريخ، صفحات المباريات، البث الداخلي،
 *  الأخبار، الصفحات القانونية…) — لأن التخطيط العام هو الجذر الذي يمرّ منه كل مسار.
 *  وهذا هو المكان الذي يوصي به Google نفسها: «الصق الكود مباشرةً بعد وسم `<head>`».
 *
 *  أين يظهر الوسمان فعلًا في HTML المُنتَج؟ (مقيس على بناء إنتاجي حقيقي 2026-10-15)
 *    • سكربت المكتبة (`async`) ⇒ **أعلى `<head>`** بعد سكربتات Next الخاصة مباشرة،
 *      فيكون أول سكربت خارجي في الرأس (React 19 يرفع كل سكربت `async` إلى الرأس).
 *    • السكربت الداخلي (تهيئة الطابور) ⇒ **آخر `<head>`** قبل `</head>` مباشرة
 *      (React 19 يضع السكربتات الداخلية المرسومة داخل الرأس في آخره حتى لا تحجب
 *      تحليل ما بعدها) — وهو سلوك إطار العمل لا اختيارنا، ولا يترتّب عليه أي فرق:
 *      فالسكربت الداخلي يبقى **داخل الرأس وقبل أي عنصر من `<body>`**، وعمله ليس إرسال
 *      طلب بل إنشاء `dataLayer` وكدس الأوامر فيه (تُفرَّغ فور وصول المكتبة).
 *    • في الحالتين: الكود في `<head>` في كل صفحة، ولا يُفقد أي قياس ولا يتأخّر أول رسم.
 *  والترتيب الفعلي موثّق ومُتحقَّق منه بأمر curl في
 *  docs/GOOGLE-ANALYTICS-2026-10-15.md.
 *
 *  لماذا وسمان `<script>` مباشران لا `next/script`؟
 *  `next/script` بأي استراتيجية (عدا beforeInteractive التي تحجب العرض) تُلحق الوسم
 *  في **نهاية `<body>`** بعد الترطيب — أي أن مكانه الفعلي لا يكون في الرأس كما طُلب،
 *  ويتأخّر تسجيل أول صفحة مشاهدة إلى ما بعد عمل React. ونفس القرار مُطبَّق في
 *  `components/AdsterraPopunder.tsx` لنفس السبب.
 *  والوسم المباشر هنا لا يعطّل شيئًا:
 *    • السكربت الخارجي `async` — لا يوقف تحليل HTML ولا يحجب الترطيب ولا يؤخّر LCP.
 *    • السكربت الداخلي سطران لا يزيدان، ولا ينتظر أي طلب شبكة (يُكدّس الأوامر في
 *      `dataLayer` وتُفرَّغ فور وصول المكتبة).
 *    • `dns-prefetch` لنطاقَي Google Analytics يُرسم في نفس الرأس (انظر `app/layout.tsx`)
 *      فلا يُدفع زمن تحليل الاسم في مسار الطلب الحرج.
 *
 *  وعند إيقاف الوسم (`NEXT_PUBLIC_GA_ENABLED=off`) أو عند معرّف غير صالح **لا يُرسم
 *  وسم واحد ولا يُرسل أي طلب إلى Google** — لا كود ولا أثر في HTML.
 *
 *  ملاحظة عن الترتيب: يُترك الوسم أول عنصر في الرأس كما طُلب، وتُترك السكربتات
 *  الإعلانية (`AdsterraPopunder`) في آخر الرأس كما نصّ كود شبكتها — فلا يتزاحم الاثنان.
 */
export default function GoogleAnalytics() {
  if (!isGoogleAnalyticsActive()) return null;

  const measurementId = resolveGaMeasurementId();
  if (!measurementId) return null;

  return (
    <>
      {/* Google tag (gtag.js) — تحميل المكتبة (async: لا يحجب العرض) */}
      <script
        id="google-analytics-loader"
        async
        src={buildGaScriptUrl(measurementId)}
      />
      {/*
        أمر التهيئة: إنشاء الطابور `dataLayer` ثم تعريف `gtag` ثم إرسال أول صفحة
        مشاهدة عبر `config`. النص نفسه يأتي من `lib/analytics/google-analytics.ts`
        (مصدر واحد) فلا يُكتب المعرّف في هذا الملف أبدًا.
        ومحتواه ثابت مولَّد من معرّف محكوم الصيغة (`G-[A-Z0-9]{4,32}`) — لا مدخل مستخدم
        فيه، ولا حاجة إلى `dangerouslySetInnerHTML`: React يرسم محتوى `<script>` كما هو
        فلا تُهرَّب علاماته (وهو ما يكسر السكربت لو استُخدم نص عادي).
      */}
      <script id="google-analytics-init">{buildGaInlineSnippet(measurementId)}</script>
    </>
  );
}
