import React from 'react';
import { ADSTERRA_POPUNDER_SCRIPT_URL, isAdsterraFormatEnabled } from '@/lib/ads/adsterra';

/**
 * ═══════════════════════════════════════════════════════════════════════════════
 *  Adsterra Popunder — الإعلان المنبثق (يُركَّب قبل إغلاق </head>)
 * ═══════════════════════════════════════════════════════════════════════════════
 *  الموضع: آخر ما يُرسم داخل <head> في التخطيط العام، أي في **كل صفحة** من الموقع،
 *  وهو الموضع الذي يطلبه كود الشبكة نفسه.
 *
 *  لماذا وسم `<script async>` مباشر هنا ولا `next/script`؟
 *  لأن `next/script` (بأي استراتيجية غير beforeInteractive) يُلحق الوسم في **نهاية
 *  <body>** بعد الترطيب — أي أن مكانه الفعلي لا يكون في الرأس كما طُلب، ويتأخّر
 *  تحميله إلى ما بعد عمل React. وهذه وحدة تعتمد على تسجيل مستمع النقر لدى الزائر
 *  من أول لحظة، فتأخيرها يعني فقدان جزء من الظهور والعمولة بلا سبب.
 *  الوسم المباشر يحقّق المطلوب بدقة مع الحفاظ على السرعة:
 *    • `async` — لا يوقف تحليل HTML ولا يؤخّر أول رسم (LCP) ولا يحجب الترطيب.
 *    • `dns-prefetch` لنطاق الشبكة في نفس الرأس (انظر app/layout.tsx) — يوفّر زمن
 *      تحليل الاسم فلا يبدأ الطلب متأخّرًا.
 *    • الصفحة لا تنتظر هذا السكربت في أي مرحلة من مراحل العرض.
 *
 *  وعند إيقاف الوحدة لا يُرسم وسم واحد — لا سكربت ولا أي أثر في HTML.
 */
export default function AdsterraPopunder() {
  if (!isAdsterraFormatEnabled('popunder')) return null;

  return <script id="adsterra-popunder" async src={ADSTERRA_POPUNDER_SCRIPT_URL} />;
}
