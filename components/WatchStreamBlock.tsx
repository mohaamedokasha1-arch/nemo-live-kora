import React from 'react';
import AdsterraBanner from './AdsterraBanner';
import SmartlinkCta from './SmartlinkCta';
import WatchStreamCta from './WatchStreamCta';
import type { WatchDestination } from '@/lib/nemo-watch';

/**
 * ═══════════════════════════════════════════════════════════════════════════════
 *  كتلة المشاهدة الموحّدة: بانر 300×250 ← زر البث ← عرض الراعي ← بانر 300×250
 * ═══════════════════════════════════════════════════════════════════════════════
 *  هذه الكتلة هي **الموضع القياسي** لزر المشاهدة في كل صفحة مباراة على البوابة
 *  (صفحة هبوط الكتالوج، صفحة البث الداخلية، وصفحة سجل المصادر)، وتضمّ:
 *    • البانر المربع 300×250 **فوق** الزر — في مجال نظر الزائر مباشرة.
 *    • زر المشاهدة الأحمر البارز (الوجهة الرسمية الموحّدة إلى منصة NEMO Sports).
 *    • زر عرض الراعي المموّل (Smartlink) بوسم إعلاني صريح، أسفل الزر لا بدلًا منه.
 *    • البانر المربع 300×250 **تحت** الزر — لالتقاط الزائر بعد قراءة الملاحظة.
 *
 *  لماذا إعلانان حول الزر تحديدًا؟
 *  الزر هو أعلى نقطة تركيز في الصفحة (المستخدم ينظر إليه مباشرة وينقر)، فوضع وحدة
 *  إعلانية قبله ومباشرة بعده يعطي أعلى معدل ظهور (Viewability) وأعلى عائد لكل ألف
 *  ظهور، وهو الشكل المعتاد في صفحات البث الرياضي.
 *
 *  لماذا لا يوجد وسم ظاهر للزائر قبل وصول الإعلان؟
 *  لأنه **لا** يوجد: `AdsterraBanner` يحجز الارتفاع بالمقاس الصحيح (250 بكسل) فلا
 *  تحدث إزاحة تخطيط (CLS)، ولا يكتب أي نص إرشادي أو صندوق فارغ داخل الصفحة.
 *  وعند إيقاف الإعلانات (`NEXT_PUBLIC_ADSTERRA_ENABLED=off` أو إيقاف وحدة البانرات)
 *  تعود الكتلة إلى زر المشاهدة وحده بلا أي أثر متبقٍّ من الوحدات.
 *
 *  ⚠️ ملاحظة تخصّ هذا الملف: وحدتا AdSense القديمتان حول الزر أُزيلتا من هنا لأن
 *  الموضعين أصبحا للبانرات المربعة من Adsterra — فلا تُعرض أربع وحدات حول زر واحد.
 *  ومساحات AdSense المُهيّأة بالبيئة (`components/AdSlot.tsx`) لا تزال تعمل كما هي
 *  في مواضع المحتوى الأخرى، وحراستها في الاختبارات قائمة.
 */
export default function WatchStreamBlock({ destination }: { destination: WatchDestination }) {
  return (
    <div className="kl-watch-block">
      <AdsterraBanner size="300x250" label="مساحة إعلانية أعلى زر البث المباشر" />
      <WatchStreamCta destination={destination} />
      <SmartlinkCta note="رابط إعلاني من راعٍ خارجي يفتح في نافذة جديدة، وللمشاهدة الرسمية استخدم الزر الأحمر بالأعلى." />
      <AdsterraBanner size="300x250" label="مساحة إعلانية أسفل زر البث المباشر" />
    </div>
  );
}
